-- Shared styling for every click-through popup (cpu / weather / wifi / battery
-- / volume / media …). Applied once via sbar.default() in bar.lua so the
-- dropdown text sits on a solid, readable panel instead of floating over
-- whatever is behind the bar. All colours come from the active tinty scheme
-- via the M.gruvbox role slots above (base01 fill, base03 border), so changing
-- the theme in tinty re-colours the popups on the next reload.
--
-- sketchybar renders a pure-black fill (0xff000000, ignoring alpha) as "no
-- fill", so nudge any all-zero-RGB colour to near-black — keeps a solid panel
-- for schemes whose base01 is literally #000000.
local function popup_fill(color)
	if (color & 0x00ffffff) == 0 then
		return (color & 0xff000000) | 0x0a0a0a
	end
	return color
end

